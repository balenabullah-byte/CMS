  const at = time => c.query("SET timestamp=UNIX_TIMESTAMP(?)",[time]);
  await at('2024-02-29 23:00:00');
  const r=await insert("INSERT INTO maintenance_requests(reporter_id,building_id,category_id,title,description) SELECT ?,?,id,'Legacy repair','Fixture' FROM maintenance_categories LIMIT 1",[member,b]);
  await c.execute("UPDATE maintenance_requests SET status='approved',reviewed_by_id=?,reviewed_at=NOW(),status_changed_by_id=? WHERE id=?",[coord,coord,r]);
